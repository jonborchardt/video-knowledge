// Video stage: the narrow, typed contract between the validated storyboard, the narration audio and the renderer.
//   storyboard scene -> script sentence ids -> narration audio (NarrationManifest) -> Timeline (frames) -> rendered frames
// Browser-safe: no node imports; the Remotion bundle imports this file.
import type { ChartSpec, VisualCategory } from '../lib/storyboard';
import type { SceneKind } from './kinds';

export const FPS = 30;
export const WIDTH = 1920;
export const HEIGHT = 1080;
/** A Short's frame (a package with a `short` block): a phone held upright. */
export const PORTRAIT = { width: 1080, height: 1920 } as const;
/** Where a Short's parts sit, in frame pixels: the badge band above `top`, the content band, the caption band, the
 *  citation block ending above YouTube's own overlay (the bottom 440 px and the right 120 px are left to it). */
export const SHORT_LAYOUT = {
  width: 1080,
  height: 1920,
  gutter: 72,
  right: 120, // left clear for the like, comment and share buttons
  top: 280, // the content band starts here (badge and format eyebrow above)
  contentBottom: 1150,
  captionTop: 1180,
  captionBottom: 1290,
  citationBottom: 1480,
} as const;
/** YouTube's limit for a Short, in measured seconds; the storyboard's estimate is capped lower (SHORT_MAX_SECONDS). */
export const SHORT_HARD_SECONDS = 180;

/** One spoken token with its time within the sentence audio, in seconds, as the provider reported it. */
export interface WordTiming {
  text: string;
  start: number;
  end: number;
}

export interface SentenceAudio {
  id: string; // sentence id
  text: string; // exactly what was synthesised; the timeline refuses it unless it equals the script sentence
  fingerprint: string; // sentenceFingerprint of the script sentence at synthesis time
  file: string; // relative to the video dir, e.g. narration/s04-<key>.mp3
  sha: string; // of the audio bytes
  duration: number; // measured seconds (ffprobe), never the provider's estimate
  words: WordTiming[]; // provider word boundaries; empty when the provider gives none
  cost?: number; // USD, when the provider is paid
}
export interface NarrationManifest {
  provider: string;
  voice: string;
  rate: string;
  model?: string;
  format: string;
  licence: string; // what the provider's terms allow: 'draft only' or 'commercial'
  cost: number; // USD for the sentences generated by a paid provider (0 for edge)
  generatedAt: string;
  sentences: SentenceAudio[];
}

/** A narration word an animation waits for: the nth occurrence (1-based) of `word` in `sentence`. */
export interface Cue {
  sentence: string;
  word: string;
  nth?: number;
}
/** Layout choices a component reads (colour, counts, flags); never figures. */
export type SceneOptions = Record<string, string | number | boolean>;
/** topics/<topic>/scripts/<slug>/video/render.json: what to render and which words drive which animations. */
export interface RenderConfig {
  scenes: string[]; // contiguous storyboard scene ids, in storyboard order
  voice: { provider: string; voice: string; rate: string };
  leadSeconds: number; // silence before the first sentence
  gapSeconds: number; // silence between sentences within a scene
  cues: Record<string, Record<string, Cue>>; // scene id -> cue name -> narration word
  kinds?: Record<string, SceneKind>; // scene id -> bespoke renderer, where the storyboard category alone does not say
  options?: Record<string, SceneOptions>; // scene id -> layout choices for that renderer
  chapters?: Record<string, string>; // scene id -> chapter title for the upload description; default: the script's sections
}

export interface TimelineWord {
  text: string;
  frame: number; // absolute frame the word starts on
  end: number; // absolute frame it ends on
}
export interface TimelineSentence {
  id: string;
  text: string;
  start: number; // absolute frame
  duration: number; // frames reserved for the audio (ceil of the measured seconds)
  audio: string; // file relative to the video dir
  audioSeconds: number;
  words: TimelineWord[];
}
export interface Citation {
  label: string; // the storyboard's on-screen label
  detail: string; // resolved from the evidence package: document name and lines, or the source's channel and URL
}
/** A cited passage, read from the corpus at timeline build, for document-excerpt scenes. */
export interface Excerpt {
  cite: string;
  doc: string; // document display name
  lines: string; // "801-866"
  text: string; // the passage as in the source file
  highlight: string | null;
}
export interface TimelineScene {
  id: string;
  order: number;
  category: VisualCategory;
  kind: SceneKind;
  start: number; // absolute frame
  duration: number; // frames, including the storyboard pause after the last sentence
  sentences: TimelineSentence[];
  cues: Record<string, number>; // cue name -> absolute frame
  onScreenText: string[];
  chart: ChartSpec | null;
  excerpt: Excerpt | null;
  citations: Citation[];
  assets: string[];
  options: SceneOptions;
}
/** The four colour roles of the owning institution's kit (brand/<key>/kit.json), which the video theme is filled from. */
export interface KitPalette {
  ground: string;
  accent: string;
  paper: string;
  ink: string;
}
// A type alias, not an interface: Remotion composition props need an implicit index signature.
export type Timeline = {
  topic: string;
  story: string;
  title: string;
  fps: number;
  width: number;
  height: number;
  durationInFrames: number;
  fingerprints: { script: string; storyboard: string; narration: string; config: string; look: string }; // look: lookFingerprint (src/shared/look.ts)
  narration: { provider: string; voice: string; rate: string; licence: string };
  palette: KitPalette;
  /** A Short: the format eyebrow, the institution that publishes it (and its key for the seal), the parent story and
   *  its question (the end card's call to action), drawn by the frame. */
  short?: { format: string; commission: string; commissionKey: string | null; question: string; parent: string };
  scenes: TimelineScene[];
};
