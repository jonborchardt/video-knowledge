// Mail transport (Milestone 2, spec §4.5 and §9 Q6; register D4): a thin wrapper over nodemailer (SMTP), imapflow
// (IMAP) and mailparser (MIME), the way ffmpeg.ts wraps a binary. The caller generates every Message-ID (the outbox's
// two-phase send needs a stable id before the first attempt); quoting and the reply grammar are the adapter's, not
// this file's. Infrastructure only: no retries, no policy, no repo import beyond node and the three libraries.
import { randomUUID } from 'node:crypto';
import nodemailer from 'nodemailer';
import { ImapFlow } from 'imapflow';
import { type ParsedMail, simpleParser } from 'mailparser';

export interface MailConfig {
  smtpHost: string;
  smtpPort: number;
  imapHost: string;
  imapPort: number;
  user: string;
  password: string;
}

/** `.env`: MAIL_SMTP_HOST, MAIL_SMTP_PORT (465), MAIL_IMAP_HOST, MAIL_IMAP_PORT (993), MAIL_USER, MAIL_PASSWORD. */
export function mailConfigFromEnv(env: NodeJS.ProcessEnv = process.env): MailConfig | null {
  const smtpHost = env.MAIL_SMTP_HOST;
  const imapHost = env.MAIL_IMAP_HOST;
  const user = env.MAIL_USER;
  const password = env.MAIL_PASSWORD;
  if (!smtpHost || !imapHost || !user || !password) return null;
  return {
    smtpHost,
    smtpPort: Number(env.MAIL_SMTP_PORT) || 465,
    imapHost,
    imapPort: Number(env.MAIL_IMAP_PORT) || 993,
    user,
    password,
  };
}

export interface OutMail {
  from: string;
  to: string;
  subject: string;
  text: string;
  html?: string;
  inReplyTo?: string;
  references?: string[];
  messageId: string; // required: generated by the caller (messageIdOf) before the send is recorded
  attachments?: { name: string; contentType: string; data: Buffer }[];
}

export interface InMail {
  uid: number;
  messageId: string;
  inReplyTo: string | null;
  references: string[];
  from: string; // the address
  subject: string;
  text: string; // the text part, or the html stripped to text when there is none
  html: string | null;
  date: string; // ISO
  raw?: string; // the source as fetched (mail-test saves a reply as a fixture); a fake leaves it out
}

export interface MailTransport {
  send(m: OutMail): Promise<{ messageId: string }>;
  fetchSince(sinceUid: number, opts?: { mailbox?: string }): Promise<InMail[]>;
}

export interface MailDeps {
  createTransport?: typeof nodemailer.createTransport;
  ImapFlow?: typeof ImapFlow;
  simpleParser?: typeof simpleParser;
}

export function libraryTransport(c: MailConfig, deps: MailDeps = {}): MailTransport {
  const create = deps.createTransport ?? nodemailer.createTransport;
  const Imap = deps.ImapFlow ?? ImapFlow;
  const parse = deps.simpleParser ?? simpleParser;
  return {
    async send(m) {
      const t = create({ host: c.smtpHost, port: c.smtpPort, secure: true, auth: { user: c.user, pass: c.password } });
      const r = await t.sendMail({
        from: m.from,
        to: m.to,
        subject: m.subject,
        text: m.text,
        ...(m.html !== undefined && { html: m.html }),
        messageId: m.messageId,
        ...(m.inReplyTo && { inReplyTo: m.inReplyTo }),
        ...(m.references?.length && { references: m.references.join(' ') }),
        ...(m.attachments?.length && {
          attachments: m.attachments.map((a) => ({ filename: a.name, contentType: a.contentType, content: a.data })),
        }),
      });
      return { messageId: r.messageId || m.messageId };
    },
    async fetchSince(sinceUid, opts = {}) {
      const client = new Imap({
        host: c.imapHost,
        port: c.imapPort,
        secure: true,
        auth: { user: c.user, pass: c.password },
        logger: false,
      });
      await client.connect();
      const lock = await client.getMailboxLock(opts.mailbox ?? 'INBOX');
      const out: InMail[] = [];
      try {
        for await (const msg of client.fetch({ uid: `${sinceUid + 1}:*` }, { uid: true, source: true })) {
          if (msg.uid <= sinceUid || !msg.source) continue; // `n:*` yields the last message even below n
          out.push({ ...toInMail(msg.uid, await parse(msg.source)), raw: msg.source.toString('utf8') });
        }
      } finally {
        lock.release();
        await client.logout();
      }
      return out.sort((a, b) => a.uid - b.uid);
    },
  };
}

export function toInMail(uid: number, p: ParsedMail): InMail {
  const refs = p.references === undefined ? [] : Array.isArray(p.references) ? p.references : [p.references];
  const html = typeof p.html === 'string' ? p.html : null;
  const text = (p.text ?? '').trim();
  return {
    uid,
    messageId: p.messageId ?? '',
    inReplyTo: p.inReplyTo ?? null,
    references: refs,
    from: p.from?.value[0]?.address ?? p.from?.text ?? '',
    subject: p.subject ?? '',
    text: text || (html ? htmlToText(html) : ''),
    html,
    date: p.date?.toISOString() ?? '',
  };
}

/** The visible text of an HTML-only reply: block ends become line breaks, tags go, common entities decode. */
export function htmlToText(html: string): string {
  return html
    .replace(/<(script|style)[\s\S]*?<\/\1>/gi, '')
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/(p|div|li|tr|h\d|blockquote)>/gi, '\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .split('\n')
    .map((l) => l.trim())
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

/** An in-memory transport for tests: what was sent, what the inbox holds, delivered by uid. `failNext` makes the next
 *  send throw before the copy is recorded ('before') or after it was (the crash after delivery, 'after'). */
export class FakeMail implements MailTransport {
  sent: OutMail[] = [];
  inbox: InMail[] = [];
  failNext: 'before' | 'after' | null = null;
  async send(m: OutMail): Promise<{ messageId: string }> {
    const fail = this.failNext;
    this.failNext = null;
    if (fail === 'before') throw new Error('smtp: connection lost before the send');
    this.sent.push({ ...m });
    if (fail === 'after') throw new Error('smtp: connection lost after the send');
    return { messageId: m.messageId };
  }
  async fetchSince(sinceUid: number): Promise<InMail[]> {
    return this.inbox.filter((m) => m.uid > sinceUid).sort((a, b) => a.uid - b.uid);
  }
  deliver(m: InMail): void {
    this.inbox.push(m);
  }
}

export const messageIdOf = (domain: string): string => `<${randomUUID()}@${domain}>`;

/** Every secret replaced before a line is logged or mailed. */
export function redact(text: string, secrets: (string | undefined)[]): string {
  let out = text;
  for (const s of secrets) if (s && s.length >= 4) out = out.split(s).join('[redacted]');
  return out;
}
